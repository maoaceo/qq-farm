const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs'); const os = require('node:os'); const path = require('node:path');
const express = require('express'); const http = require('node:http');
const { generateKeyPair, exportJWK, createLocalJWKSet, SignJWT } = require('jose');
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'farm-oidc-'));
const paths = require('../dist/config/runtime-paths'); paths.getDataFile = n => path.join(tmp, n); paths.ensureDataDir = () => tmp;
const users = require('../dist/models/user-store');
const oidc = require('../dist/services/oidc');
const provider = { id: 'oidc', name: 'Test', issuer: 'https://issuer.example', clientId: 'client', clientSecret: 'test-only', scopes: 'openid email profile' };
const metadata = { issuer: provider.issuer, authorization_endpoint: 'https://issuer.example/authorize', token_endpoint: 'https://issuer.example/token', jwks_uri: 'https://issuer.example/jwks' };

test('OIDC signature and claim validation', async () => {
  const { privateKey, publicKey } = await generateKeyPair('RS256');
  const jwk = await exportJWK(publicKey); jwk.kid = 'k1';
  const keys = createLocalJWKSet({ keys: [jwk] });
  const sign = async (extra = {}) => new SignJWT({ sub: 'subject-1', nonce: 'n1', ...extra }).setProtectedHeader({ alg: 'RS256', kid: 'k1' }).setIssuer(provider.issuer).setAudience(provider.clientId).setIssuedAt().setExpirationTime('5m').sign(privateKey);
  assert.deepEqual(await oidc.verifySignedIdentity(provider, await sign(), 'n1', keys), { issuer: provider.issuer, subject: 'subject-1' });
  await assert.rejects(oidc.verifySignedIdentity(provider, await sign(), 'wrong', keys));
  await assert.rejects(oidc.verifySignedIdentity({ ...provider, issuer: 'https://other.example' }, await sign(), 'n1', keys));
  await assert.rejects(oidc.verifySignedIdentity({ ...provider, clientId: 'other-client' }, await sign(), 'n1', keys));
  await assert.rejects(oidc.verifySignedIdentity(provider, await sign({ azp: 'other-client' }), 'n1', keys));
  await assert.rejects(oidc.verifySignedIdentity(provider, await sign({ nonce: undefined }), 'n1', keys));
  const expired = await new SignJWT({ sub: 's', nonce: 'n1' }).setProtectedHeader({ alg: 'RS256', kid: 'k1' }).setIssuer(provider.issuer).setAudience('client').setIssuedAt().setExpirationTime(Math.floor(Date.now()/1000)-60).sign(privateKey);
  await assert.rejects(oidc.verifySignedIdentity(provider, expired, 'n1', keys));
  const bad = await generateKeyPair('RS256');
  const forged = await new SignJWT({ sub: 's', nonce: 'n1' }).setProtectedHeader({ alg: 'RS256', kid: 'k1' }).setIssuer(provider.issuer).setAudience('client').setIssuedAt().setExpirationTime('5m').sign(bad.privateKey);
  await assert.rejects(oidc.verifySignedIdentity(provider, forged, 'n1', keys));
});

test('browser-bound OAuth flow, auto-registration and one-time handoff', async t => {
  process.env.AUTH_PUBLIC_URL = 'https://farm.example'; process.env.OIDC_AUTO_REGISTER = 'true';
  const original = { providers: oidc.providers, discover: oidc.discover, exchange: oidc.exchange };
  oidc.providers = () => [provider]; oidc.discover = async () => metadata;
  oidc.exchange = async (_p, _d, code, nonce, verifier) => { assert.equal(code, 'valid-code'); assert.ok(nonce); assert.ok(verifier); return { issuer: provider.issuer, subject: 'external-alice' }; };
  const ctx = require('../dist/controllers/admin/context').createAdminContext({});
  const app = express(); app.use(express.json()); require('../dist/controllers/admin/auth-routes').mountAuthRoutes(app, ctx);
  const server = http.createServer(app); await new Promise(r => server.listen(0, '127.0.0.1', r));
  const base = `http://127.0.0.1:${server.address().port}`;
  t.after(async () => { Object.assign(oidc, original); delete process.env.AUTH_PUBLIC_URL; delete process.env.OIDC_AUTO_REGISTER; server.closeAllConnections(); await new Promise(r => server.close(r)); fs.rmSync(tmp, { recursive: true, force: true }); });
  const request = (url, options = {}) => fetch(base+url, { redirect: 'manual', ...options });
  const start = await request('/api/oauth/oidc/start'); assert.equal(start.status,302);
  const loc = new URL(start.headers.get('location')); const state = loc.searchParams.get('state');
  assert.equal(loc.searchParams.get('code_challenge_method'), 'S256'); assert.equal(loc.searchParams.get('redirect_uri'), 'https://farm.example/api/oauth/oidc/callback');
  assert.ok(start.headers.get('set-cookie').includes('HttpOnly')); assert.ok(start.headers.get('set-cookie').includes('Secure'));
  const cookie = start.headers.get('set-cookie').split(';')[0];
  const cb = `/api/oauth/oidc/callback?state=${state}&code=valid-code`;
  assert.equal((await request(cb)).status,400);
  assert.equal((await request(`/api/oauth/google/callback?state=${state}&code=valid-code`, { headers: { cookie } })).status,400);
  const response = await request(cb, { headers: { cookie } }); assert.equal(response.status,302);
  assert.equal(response.headers.get('location'),'https://farm.example/login?oauth=complete'); assert.ok(!response.headers.get('location').includes('token='));
  assert.equal((await request(cb, { headers: { cookie } })).status,400);
  const tickets = response.headers.getSetCookie().find(v=>v.startsWith('farm_oauth_ticket=')); const ticket = tickets.split(';')[0];
  assert.equal((await request('/api/oauth/exchange',{ method:'POST',headers: { cookie:ticket, origin:'https://attacker.example' } })).status,403);
  const exchange = await request('/api/oauth/exchange',{ method:'POST',headers: { cookie:ticket, origin:'https://farm.example' } }); assert.equal(exchange.status,200);
  const data = await exchange.json(); assert.equal(data.data.role,'user');
  const me = await request('/api/user/me',{headers: {'x-admin-token':data.data.token}}); const user = (await me.json()).data;
  assert.equal(user.role,'user'); assert.match(user.username,/^sso_/);
  assert.equal((await request('/api/oauth/exchange',{method:'POST',headers:{cookie:ticket,origin:'https://farm.example'}})).status,401);
  assert.equal(users.federated(provider.issuer,'external-alice').id,user.id);
  assert.notEqual(users.federated('https://second.example','external-alice').id,user.id);
  assert.equal(users.validate(user.username,'','sso-test').error,'invalid_credentials');
  users.update(user.id,{disabled:true}); assert.throws(()=>users.federated(provider.issuer,'external-alice'));
  process.env.OIDC_AUTO_REGISTER='false'; assert.throws(()=>users.federated(provider.issuer,'new-subject'));
  assert.equal(users.federated('https://second.example','external-alice').role,'user');
});
